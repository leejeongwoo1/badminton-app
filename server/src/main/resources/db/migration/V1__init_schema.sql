-- =====================================================================
-- V1: 초기 스키마 (docs/diagram/ERD.drawio 기준)
--
-- 규칙
--  * PK      : BIGINT IDENTITY (DB가 자동 증가, JPA GenerationType.IDENTITY)
--  * 시각    : TIMESTAMPTZ (시간대 포함)
--  * ENUM    : VARCHAR + CHECK 제약 (PostgreSQL 전용 ENUM 타입은 값 추가가 번거롭고 JPA와 궁합이 나빠서)
--  * 상태값  : 상태 다이어그램과 1:1로 대응
-- =====================================================================

-- ---------------------------------------------------------------------
-- 사용자
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    nickname        VARCHAR(30)  NOT NULL UNIQUE,
    gender          VARCHAR(10)  NOT NULL CHECK (gender IN ('MALE', 'FEMALE')),
    grade           VARCHAR(10)  NOT NULL CHECK (grade IN ('BEGINNER', 'D', 'C', 'B', 'A')),  -- 가입 시 1회, 수정 불가
    mmr             INT          NOT NULL,                                                       -- 초기값 = 급수별 기준값
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 체육관 / 관리자 / 코트
-- ---------------------------------------------------------------------
CREATE TABLE gyms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)  NOT NULL,
    address         VARCHAR(255)  NOT NULL,
    latitude        NUMERIC(9, 6) NOT NULL,
    longitude       NUMERIC(9, 6) NOT NULL,
    auth_radius_m   INT           NOT NULL CHECK (auth_radius_m > 0),
    open_time       TIME          NOT NULL,
    close_time      TIME          NOT NULL,
    created_by      BIGINT        NOT NULL REFERENCES users (id),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE gym_managers (
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    gym_id          BIGINT      NOT NULL REFERENCES gyms (id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, gym_id)
);

CREATE TABLE courts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id          BIGINT      NOT NULL REFERENCES gyms (id),
    court_number    INT         NOT NULL CHECK (court_number > 0),
    status          VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'IN_USE')),
    UNIQUE (gym_id, court_number)                 -- 한 체육관에 "3번 코트"는 하나
);

-- ---------------------------------------------------------------------
-- 체크인 (방문 1회 = 1행, 사용자 상태를 가짐)
-- ---------------------------------------------------------------------
CREATE TABLE check_ins (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    gym_id          BIGINT      NOT NULL REFERENCES gyms (id),
    status          VARCHAR(20) NOT NULL DEFAULT 'RESTING' CHECK (status IN (
                        'RESTING', 'QUEUED', 'MATCHED', 'PLAYING', 'AWAITING_RESULT', 'CHECKED_OUT')),
    checked_in_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_active_at  TIMESTAMPTZ NOT NULL DEFAULT now(),   -- 체크인·매칭 시작·게임 시작 때 갱신 (90분 자동 체크아웃 기준)
    checked_out_at  TIMESTAMPTZ
);

-- 사용자당 "진행 중인 체크인"은 1개만 (부분 유니크 인덱스)
CREATE UNIQUE INDEX uq_check_ins_active_user ON check_ins (user_id) WHERE checked_out_at IS NULL;
-- 자동 체크아웃 스케줄러용
CREATE INDEX ix_check_ins_active_last_active ON check_ins (last_active_at) WHERE checked_out_at IS NULL;

-- ---------------------------------------------------------------------
-- 게임
-- ---------------------------------------------------------------------
CREATE TABLE games (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id          BIGINT      NOT NULL REFERENCES gyms (id),
    court_id        BIGINT      REFERENCES courts (id),        -- 코트 대기 중이면 NULL
    mode            VARCHAR(20) NOT NULL CHECK (mode IN ('MEN_DOUBLES', 'WOMEN_DOUBLES', 'MIXED_DOUBLES', 'ANY')),
    status          VARCHAR(20) NOT NULL DEFAULT 'WAITING_COURT' CHECK (status IN (
                        'WAITING_COURT', 'IN_PROGRESS', 'COLLECTING_SCORES', 'DISPUTED',
                        'CONFIRMED', 'VOIDED', 'CANCELLED')),
    matched_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at      TIMESTAMPTZ,                               -- 코트 배정 = 게임 시작
    ended_at        TIMESTAMPTZ,                               -- 첫 점수 제출 시각
    confirmed_at    TIMESTAMPTZ,
    team_a_score    INT CHECK (team_a_score BETWEEN 0 AND 30),
    team_b_score    INT CHECK (team_b_score BETWEEN 0 AND 30)
);

-- 체육관별 코트 대기 게임 / 스케줄러 조회용
CREATE INDEX ix_games_gym_status ON games (gym_id, status);

CREATE TABLE game_players (
    game_id         BIGINT     NOT NULL REFERENCES games (id),
    user_id         BIGINT     NOT NULL REFERENCES users (id),
    team            VARCHAR(1) NOT NULL CHECK (team IN ('A', 'B')),
    is_no_show      BOOLEAN    NOT NULL DEFAULT false,
    mmr_before      INT,
    mmr_after       INT,
    PRIMARY KEY (game_id, user_id)
);

CREATE INDEX ix_game_players_user ON game_players (user_id);

-- ---------------------------------------------------------------------
-- 매칭 대기열
-- ---------------------------------------------------------------------
CREATE TABLE queue_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_in_id     BIGINT      NOT NULL REFERENCES check_ins (id),
    status          VARCHAR(20) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'MATCHED', 'CANCELLED')),
    enqueued_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    game_id         BIGINT      REFERENCES games (id),        -- 매칭되면 채워짐
    left_at         TIMESTAMPTZ
);

-- "지금 기다리는 사람"만 대기 순서대로 빠르게 찾기 (부분 인덱스)
CREATE INDEX ix_queue_entries_waiting ON queue_entries (enqueued_at) WHERE status = 'WAITING';
CREATE INDEX ix_queue_entries_check_in ON queue_entries (check_in_id);

CREATE TABLE queue_entry_modes (
    queue_entry_id  BIGINT      NOT NULL REFERENCES queue_entries (id),
    mode            VARCHAR(20) NOT NULL CHECK (mode IN ('MEN_DOUBLES', 'WOMEN_DOUBLES', 'MIXED_DOUBLES', 'ANY')),
    PRIMARY KEY (queue_entry_id, mode)
);

-- ---------------------------------------------------------------------
-- 점수 제출 (1인 1행, 수정 대기 중엔 UPDATE)
-- ---------------------------------------------------------------------
CREATE TABLE score_submissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id         BIGINT      NOT NULL REFERENCES games (id),
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    team_a_score    INT         NOT NULL CHECK (team_a_score BETWEEN 0 AND 30),
    team_b_score    INT         NOT NULL CHECK (team_b_score BETWEEN 0 AND 30),
    submitted_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (game_id, user_id)
);
